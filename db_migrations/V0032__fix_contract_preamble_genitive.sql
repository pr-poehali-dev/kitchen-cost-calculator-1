-- V0032: Исправляем преамбулу договора — склонение имён, название фирмы
UPDATE t_p24868917_kitchen_cost_calcula.doc_templates
SET blocks = (
  SELECT jsonb_agg(
    CASE
      WHEN b->>'id' = 'intro' THEN
        b || jsonb_build_object('content',
          '{{компания}}, в лице менеджера {{менеджер}}, действующего на основании доверенности № {{номер_доверенности}} от {{дата_доверенности}}, именуемый в дальнейшем «Подрядчик», и гр. {{имя_клиента_рп}}, именуемый (ая) в дальнейшем «Заказчик», действующий (ая) как физическое лицо, с одной стороны, отдельно именуемые – «Сторона», а совместно именуемые – «Стороны», заключили настоящий Договор о нижеследующем:'
        )
      ELSE b
    END
  )
  FROM jsonb_array_elements(blocks) AS b
),
updated_at = now()
WHERE doc_type = 'contract' AND is_default = true;
